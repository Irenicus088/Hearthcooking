#!/usr/bin/env python3
"""Generates Hearthcooking.esp (ESL-flagged, no scripts) and src/plugin/EspIds.h.

Records:
  ALCH  HC_Dish000 .. HC_Dish299 - empty dishes. The DLL makes each one a Burnt, Hearty or Masterwork copy of a game
        dish the first time you cook it to that tier (name, mesh, weight, effects, value, keywords), and remembers which
        is which in the SKSE co-save, so they keep their identity across saves and load orders. They are real forms in
        a plugin, so the game saves them in your inventory like any other food.

Header: version 1.70, form version 44, so the plugin loads on every version from 1.5.97 up (1.6.1130+ writes 1.71,
which older games refuse; nothing here needs it).

Usage: python3 tools/make_esp.py
"""
import os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = 0x01000000
FIRST = 0x800
SLOTS = 300


def sub(tag, data):
    return tag.encode() + struct.pack("<H", len(data)) + data


def zstr(s):
    return s.encode("cp1252") + b"\0"


def record(tag, formid, payload, flags=0):
    return tag.encode() + struct.pack("<IIIHHHH", len(payload), flags, formid, 0, 0, 44, 0) + payload


def group(label, payload, gtype=0):
    lab = label.encode() if isinstance(label, str) else label
    return b"GRUP" + struct.pack("<I4siHHI", 24 + len(payload), lab, gtype, 0, 0, 0) + payload


def main():
    body = b""
    for k in range(SLOTS):
        # ENIT: value, flags (cost override 0x1 | food 0x2), addiction, addiction chance, consume sound
        p = (sub("EDID", zstr(f"HC_Dish{k:03d}")) + sub("OBND", struct.pack("<6h", -4, -4, 0, 4, 4, 3)) +
             sub("FULL", zstr("Hearthcooking Dish")) + sub("MODL", zstr("Hearthcooking\\Bowl.nif")) +
             sub("DATA", struct.pack("<f", 0.5)) + sub("ENIT", struct.pack("<iIIfI", 1, 0x3, 0, 0.0, 0)))
        body += record("ALCH", M | (FIRST + k), p)
    esp_body = group("ALCH", body)
    hedr = struct.pack("<fiI", 1.70, SLOTS + 1, FIRST + SLOTS)
    tes4 = (sub("HEDR", hedr) + sub("CNAM", zstr("evodube")) +
            sub("SNAM", zstr("Hearthcooking - cook by hand at the pot, the spit and the oven (needs Hearthcooking.dll)")) +
            sub("MAST", zstr("Skyrim.esm")) + sub("DATA", b"\0" * 8))
    esp = record("TES4", 0, tes4, flags=0x200) + esp_body  # 0x200 = ESL (light plugin)
    open(os.path.join(ROOT, "Hearthcooking.esp"), "wb").write(esp)
    L = ["#pragma once", "// Generated by tools/make_esp.py - keep in sync with Hearthcooking.esp.", "",
         "namespace EspIds", "{", '\tinline constexpr const char* kPlugin = "Hearthcooking.esp";',
         f"\tinline constexpr RE::FormID kFirstDish = 0x{FIRST:X};", f"\tinline constexpr int kDishSlots = {SLOTS};", "}", ""]
    open(os.path.join(ROOT, "src", "plugin", "EspIds.h"), "w").write("\n".join(L))
    print(f"wrote Hearthcooking.esp ({len(esp)} bytes, {SLOTS} dishes) and src/plugin/EspIds.h")


if __name__ == "__main__":
    main()
